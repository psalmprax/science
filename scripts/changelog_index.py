#!/usr/bin/env python3
"""A short index of CHANGELOG.md: its sections and the title of every entry, in order.

``CHANGELOG.md`` is nearly ten thousand lines. This writes ``docs/CHANGELOG_INDEX.md`` from it: one line for each
entry of the current ``[Unreleased]`` block (its bold title, or its first words) under its section, then one line
for each dated block of the historical notes. The index is generated, never edited:

    python scripts/changelog_index.py --write     # after adding or retitling an entry
    python scripts/changelog_index.py --check     # fails if the index is not the one the changelog gives

Status: audit-only
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CHANGELOG = ROOT / "CHANGELOG.md"
INDEX = ROOT / "docs" / "CHANGELOG_INDEX.md"
TITLE_WIDTH = 150
_BOLD = re.compile(r"^- \*\*(.+?)\*\*")


def title_of(lines: list[str], start: int) -> str:
    """The entry's bold title (which may run over several lines), or the words of its first line."""
    own = [lines[start]]
    for line in lines[start + 1:start + 6]:                   # the entry's own continuation lines: indented, not a sub-point
        if not line.startswith("  ") or line.lstrip().startswith("- "):
            break
        own.append(line)
    match = _BOLD.match(" ".join(line.strip() for line in own))
    text = match.group(1) if match else lines[start][2:]
    text = re.sub(r"\s+", " ", text).strip().rstrip(".:")
    return text if len(text) <= TITLE_WIDTH else text[:TITLE_WIDTH - 1].rstrip() + "…"


def build(text: str) -> str:
    lines = text.splitlines()
    out = ["# Index of CHANGELOG.md", "",
           "Generated by `scripts/changelog_index.py` from [`CHANGELOG.md`](../CHANGELOG.md); do not edit. One line for each "
           "entry of the current block, then one line for each dated block of the historical notes, in the changelog's order.", ""]
    blocks = entries = 0
    older: list[str] = []
    for number, line in enumerate(lines):
        if line.startswith("## "):
            blocks += 1
            if blocks == 1:
                out += [f"## {line[3:].strip()}", ""]
            else:
                older.append(f"- {line[3:].strip()}")
        elif blocks == 1 and line.startswith("### "):
            out += ["", f"### {line[4:].strip()}", ""]
        elif blocks == 1 and line.startswith("- "):
            out.append(f"- {title_of(lines, number)}")
            entries += 1
    out += ["", "## Earlier blocks", "", *older, "", f"{entries} entries in the current block; {len(older)} earlier blocks."]
    return re.sub(r"\n{3,}", "\n\n", "\n".join(out)) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    wanted = build(CHANGELOG.read_text(encoding="utf-8"))
    if args.write:
        INDEX.write_text(wanted, encoding="utf-8")
        print(f"wrote {INDEX.relative_to(ROOT)}: {wanted.count(chr(10))} lines")
        return 0
    if not INDEX.exists() or INDEX.read_text(encoding="utf-8") != wanted:
        print("docs/CHANGELOG_INDEX.md is not the index of CHANGELOG.md: run scripts/changelog_index.py --write")
        return 1
    print("docs/CHANGELOG_INDEX.md matches CHANGELOG.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
