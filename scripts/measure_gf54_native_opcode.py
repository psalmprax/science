#!/usr/bin/env python3
"""Price the 54-AND product as a `kickmix` policy, and ask what it reaches.

`benchmarks/quantum_compilation/gf54_mul_kickmix.json` measured the 54-AND multiply
by swapping `ixor_gf2_mul` for a Python gate stream (`scripts/gf54_mul.py`). That
substitution reaches exactly one instruction: every other product in the decoder —
the five products of the Itoh-Tsujii inversion inside Chien search, and the quotient
sweep's — stayed on the built-in 63-AND Karatsuba, because they are emitted by
native generators that the Python mixin cannot intercept.

This script measures the same multiply as a *builder policy* instead
(`builder.gf_product = "and54"`, generated by `gen_gf54_mul` inside the extension),
which reaches all three products. Four questions, in the order they have to be
answered:

1. **Does the native opcode cost what the gate stream cost?** Unit counts for the
   controlled multiply, the uncontrolled one, the inversion pair and the division,
   against the built-in recursion at the same entries.
2. **Is it the same unitary?** Function check on random basis states for the
   multiply, the inversion and the division: values, operands, workspace, phase.
3. **Does it lower the reference circuit's own total?** The reference decoder built
   twice at the pinned instance, differenced. The reference's Forney step runs an
   inversion at every one of its 4,095 positions, and that inversion is five
   products, so this is where a multiply policy shows up if it shows up anywhere.
4. **What does it do to the six-lever arm?** The same arm as the earlier record,
   with the policy set instead of the mixin, so the two arms' difference is the
   multiply and nothing else.

Everything is measured on the local MR-capable build. No receipt, no score: the
pinned binary has no `MR`, and `gen_gf54_mul` clears its windows with it.

Example::

    /dev/shm/qvcc-venv313/bin/python scripts/build_kickmix_mr.py
    /dev/shm/qvcc-venv313/bin/python scripts/measure_gf54_native_opcode.py
"""
