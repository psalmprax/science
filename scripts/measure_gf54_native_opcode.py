def native_builder(base: type, product: str) -> type:
    """The real builder with `gf_product` set at construction time.

    A subclass rather than a post-hoc assignment because the arms script builds its
    own builder internally; overriding `__init__` is the only place that catches it.
    """
    class WithProduct(base):
        def __init__(self, *args, **kwargs):
            super().__init__(*args, **kwargs)
            self.gf_product = product

    WithProduct.__name__ = f"{base.__name__}[{product}]"
    return WithProduct


def scoped_policy_builder(base: type, methods: tuple[str, ...]) -> type:
    """The builder with the 54-AND product only inside the named entry points.

    Every product the decoder emits reaches `gen_gf_mul` through one of a few builder
    methods: the multiply proper, the division, the inversion, the phase product that
    closes an inversion. Flipping the policy around one of them leaves everything else on
    the built-in product, so differencing this circuit against
    `native_builder(base, "karatsuba")` prices that entry point's products and nothing
    else -- and both circuits stay correct, which is what makes the difference a
    measurement rather than an ablation.
    """

    def swap(call):
        @functools.wraps(call)
        def wrapper(self, *args, **kwargs):
            before = self.gf_product
            self.gf_product = "and54"
            try:
                return call(self, *args, **kwargs)
            finally:
                self.gf_product = before

        return wrapper

    namespace = {name: swap(getattr(base, name)) for name in methods}
    namespace["__name__"] = f"{base.__name__}[{'|'.join(methods)}]"
    return type(f"Scoped_{'_'.join(methods)}", (base,), namespace)


def forney_builder(base: type) -> type:
    """The Forney inversion block: five products per position plus the phase product."""
    return scoped_policy_builder(base, ("init_gf2_inverse_with_scaffold",
                                        "gf2_phase_by_product"))


def division_builder(base: type) -> type:
    """The change-of-basis / quotient-sweep division, and nothing else."""
    return scoped_policy_builder(base, ("init_gf2_div_with_scaffold",))
    ForneyAnd54.__name__ = f"{base.__name__}[forney_and54]"
    return ForneyAnd54


def toffoli_like(circuit) -> int:
    stats = dict(circuit.operation_statistics())
    return int(sum(stats.get(name, 0) for name in ("CCX", "CSWAP", "AND")))


def _stats(circuit) -> dict:
    return {k: int(v) for k, v in dict(circuit.operation_statistics()).items() if v}


# ------------------------------------------------------------------- unit costs


def unit_costs(km, base: type, degree: int) -> dict:
    """Static counts at each entry point, for both product policies."""
    field = km.GF2Field(degree)
    out: dict = {"controlled_multiply": {}, "multiply": {}, "inversion": {}, "division": {}}
    for label, product in (("builtin", "karatsuba"), ("and54", "and54")):
        cls = native_builder(base, product)

        builder = cls()
        lhs = builder.create_quantum_register(degree, name="L")
        rhs = builder.create_quantum_register(degree, name="R")
        target = builder.create_quantum_register(degree, name="T")
        control = builder.create_quantum_register(1, name="C")
        builder.ixor_gf2_mul(lhs, rhs, target=target, field=field, control=control[0])
        circuit = builder.finish_circuit()
        registers = 3 * degree + 1
        out["controlled_multiply"][label] = {
            **_stats(circuit), "toffoli_like": toffoli_like(circuit),
            "qubits": circuit.num_qubits, "workspace": circuit.num_qubits - registers,
        }

        builder = cls()
        lhs = builder.create_quantum_register(degree, name="L")
        rhs = builder.create_quantum_register(degree, name="R")
        target = builder.create_quantum_register(degree, name="T")
        builder.ixor_gf2_mul(lhs, rhs, target=target, field=field)
        circuit = builder.finish_circuit()
        registers = 3 * degree
        out["multiply"][label] = {
            **_stats(circuit), "toffoli_like": toffoli_like(circuit),
            "qubits": circuit.num_qubits, "workspace": circuit.num_qubits - registers,
        }

        builder = cls()
        source = builder.create_quantum_register(degree, name="S")
        target = builder.create_quantum_register(degree, name="T")
        _, scaffold = builder.init_gf2_inverse_with_scaffold(source, target=target, field=field)
        builder.del_gf2_inverse_with_scaffold(source, target=target, scaffold=scaffold,
                                              field=field)
        circuit = builder.finish_circuit()
        registers = 2 * degree + len(scaffold)
        out["inversion"][label] = {
            **_stats(circuit), "toffoli_like": toffoli_like(circuit),
            "qubits": circuit.num_qubits, "workspace": circuit.num_qubits - registers,
        }

        builder = cls()
        lhs = builder.create_quantum_register(degree, name="L")
        rhs = builder.create_quantum_register(degree, name="R")
        target = builder.create_quantum_register(degree, name="T")
        _, scaffold = builder.init_gf2_div_with_scaffold(lhs, rhs, target=target, field=field)
        circuit = builder.finish_circuit()
        registers = 3 * degree + len(scaffold)
        out["division"][label] = {
            **_stats(circuit), "toffoli_like": toffoli_like(circuit),
            "qubits": circuit.num_qubits, "workspace": circuit.num_qubits - registers,
        }
    return out


# --------------------------------------------------------------------- function


def _bits(values, width: int) -> np.ndarray:
    return np.array([[(int(v) >> i) & 1 for i in range(width)] for v in values], dtype=bool)


def function_check(km, base: type, degree: int, samples: int, seed: int) -> dict:
    """Run each entry point on random basis states and check every register it touches."""
    field = km.GF2Field(degree)
    rng = np.random.default_rng(seed)
    lhs_in = rng.integers(0, 1 << degree, samples)
    rhs_in = rng.integers(0, 1 << degree, samples)
    control_in = rng.integers(0, 2, samples)

    cases = {
        "multiply": {
            "build": lambda b: (b.create_quantum_register(degree, name="L"),
                                b.create_quantum_register(degree, name="R"),
                                b.create_quantum_register(degree, name="T"),
                                b.create_quantum_register(1, name="C")),
            "emit": lambda b, regs: b.ixor_gf2_mul(regs[0], regs[1], target=regs[2],
                                                  field=field, control=regs[3][0]),
            "target": lambda regs: regs[2],
            "write": lambda regs: (list(regs[0]) + list(regs[1]), lhs_in, rhs_in),
            "controls": lambda regs: (regs[3][0], control_in),
            "want": lambda: np.array([field.mul(int(lhs_in[i]), int(rhs_in[i]))
                                      if control_in[i] else 0 for i in range(samples)]),
        },
        "inversion": {
            "build": lambda b: (b.create_quantum_register(degree, name="S"),
                                b.create_quantum_register(degree, name="T")),
            "emit": lambda b, regs: b.init_gf2_inverse_with_scaffold(
                regs[0], target=regs[1], field=field)[1],
            "target": lambda regs: regs[1],
            "write": lambda regs: (list(regs[0]), lhs_in, None),
            "controls": lambda regs: None,
            "want": lambda: np.array([0 if int(v) == 0 else field.invert(int(v))
                                      for v in lhs_in]),
        },
        "division": {
            "build": lambda b: (b.create_quantum_register(degree, name="L"),
                                b.create_quantum_register(degree, name="R"),
                                b.create_quantum_register(degree, name="T")),
            "emit": lambda b, regs: b.init_gf2_div_with_scaffold(
                regs[0], regs[1], target=regs[2], field=field)[1],
            "target": lambda regs: regs[2],
            "write": lambda regs: (list(regs[0]) + list(regs[1]), lhs_in, rhs_in),
            "controls": lambda regs: None,
            "want": lambda: np.array([0 if int(rhs_in[i]) == 0
                                      else field.div(int(lhs_in[i]), int(rhs_in[i]))
                                      for i in range(samples)]),
        },
    }

    results = {}
    for name, case in cases.items():
        builtin = native_builder(base, "karatsuba")
        output = {}
        for label, product in (("builtin", "karatsuba"), ("native_and54", "and54")):
            builder = native_builder(base, product)()
            regs = case["build"](builder)
            # The scaffold is the routine's other output, not leftover workspace.
            scaffold = case["emit"](builder, regs)
            circuit = builder.finish_circuit()
            target = case["target"](regs)
            written, first, second = case["write"](regs)
            written_values = (_bits(first, degree) if second is None else
                              np.concatenate([_bits(first, degree), _bits(second, degree)],
                                             axis=1)).T

            sim = km.Simulator(batch_size=samples, seed=seed)
            sim.use_same_registers_as(circuit)
            sim.write_across_shots(km.array(written), written_values)
            if (controls := case["controls"](regs)) is not None:
                bit, values = controls
                sim.write_across_shots(km.array([bit]),
                                       values.astype(bool).reshape(1, -1))
            sim.do(circuit)

            read = sim.read_across_shots(km.array(list(target)))
            got = (read.T * (1 << np.arange(degree))).sum(axis=1)
            want = case["want"]()
            everything = sim.read_across_shots(
                km.array([km.q(i) for i in range(circuit.num_qubits)])).T
            kept = [q.id for q in written]
            known = set(kept) | {q.id for q in target}
            if scaffold is not None:
                known |= {q.id for q in scaffold}
            if (controls := case["controls"](regs)) is not None:
                known.add(controls[0].id)
            other = [i for i in range(circuit.num_qubits) if i not in known]
            output[label] = {
                "samples": samples,
                "toffoli_like": toffoli_like(circuit),
                "value_mismatches": int(np.abs(got - want).astype(bool).sum()),
                "operands_restored": bool(np.array_equal(
                    everything[:, kept], written_values.T)),
                "workspace_back_to_zero": bool(not everything[:, other].any()),
                "phase_flips": int(sim.read_phase_flipped_across_shots().sum()),
            }
        results[name] = output
    return results


def check_function(results: dict) -> list[str]:
    problems = []
    for name, rows in results.items():
        row = rows["native_and54"]
        if row["value_mismatches"]:
            problems.append(f"{name}: {row['value_mismatches']} wrong values")
        if not row["operands_restored"]:
            problems.append(f"{name}: operands not restored")
        if not row["workspace_back_to_zero"]:
            problems.append(f"{name}: workspace not back to zero")
        if row["phase_flips"]:
            problems.append(f"{name}: {row['phase_flips']} phase flips")
    return problems


# -------------------------------------------------------------------- circuits


def build_reference(km, arms, shim, n: int, degree: int, m: int):
    """The reference decoder, exactly as `dqi_reference_circuit.build_reference_circuit`."""
    builder = shim.CircuitBuilder()
    syndromes = [builder.create_quantum_register(degree, name=f"S{i}") for i in range(n)]
    error_mbuc = [builder.create_classical_register(degree, name=f"E{j}") for j in range(m)]
    arms.DR.ProosAndZalkaDecoder(n, km.GF2Field(degree)).build_syndrome_decoding_mbuc(
        builder, syndromes=syndromes, error_mbuc=error_mbuc,
        n_iters=arms.DR.default_n_iters(n))
    return builder.finish_circuit(), syndromes, error_mbuc


def build_arm(km, arms, shim, flags, n: int, degree: int, m: int):
    decoder = arms.MRGatedDecoder(n, km.GF2Field(degree), **flags)
    builder = shim.CircuitBuilder()
    syndromes = [builder.create_quantum_register(degree, name=f"S{i}") for i in range(n)]
    error_mbuc = [builder.create_classical_register(degree, name=f"E{j}") for j in range(m)]
    decoder.build_syndrome_decoding_mbuc(
        builder, syndromes=syndromes, error_mbuc=error_mbuc,
        n_iters=arms.DR.default_n_iters(n))
    return builder.finish_circuit(), syndromes, error_mbuc


def simulate(km, circuit, syndromes, error_mbuc, syndromes_in, mbuc_in, degree: int,
             shots: int, seed: int = 99) -> dict:
    sim = km.Simulator(batch_size=shots, seed=seed, counting_operations=True)
    sim.use_same_registers_as(circuit)
    flat_syndromes = km.array([q for register in syndromes for q in register])
    flat_errors = km.array([b for register in error_mbuc for b in register])
    from verify_submission_dqi import to_bits
    sim.write_across_shots(flat_syndromes, to_bits(syndromes_in, degree))
    sim.write_across_shots(flat_errors, to_bits(mbuc_in, degree))
    sim.do(circuit)
    syndrome_ids = {q.id for register in syndromes for q in register}
    junk_ids = [i for i in range(circuit.num_qubits) if i not in syndrome_ids]
    per_shot = [dict(sim.operation_statistics(i)) for i in range(shots)]
    return {
        "syndromes": sim.read_across_shots(flat_syndromes),
        "junk": sim.read_across_shots([km.q(i) for i in junk_ids]),
        "phase": sim.read_phase_flipped_across_shots(),
        "toffoli_per_shot": [int(sim.operation_statistics(i).num_toffoli_like)
                             for i in range(shots)],
        "ccx_per_shot": [int(row.get("CCX", 0)) for row in per_shot],
        "cswap_per_shot": [int(row.get("CSWAP", 0)) for row in per_shot],
    }


def is_correct(out: dict, reference: dict, reference_inputs: np.ndarray) -> bool:
    return bool(np.array_equal(out["syndromes"], reference["syndromes"])
                and np.array_equal(out["phase"], reference["phase"])
                and np.array_equal(out["syndromes"], reference_inputs)
                and not out["junk"].any())


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--m", type=int, default=4095)
    parser.add_argument("--n", type=int, default=70)
    parser.add_argument("--degree", type=int, default=12)
    parser.add_argument("--shots", type=int, default=64)
    parser.add_argument("--checks", type=int, default=32)
    parser.add_argument("--skip-circuits", action="store_true",
                        help="unit costs and function checks only")
    parser.add_argument("--kickmix-build", type=Path, default=DEFAULT_BUILD)
    parser.add_argument("--record", type=Path, default=DEFAULT_RECORD)
    args = parser.parse_args()

    runner = load_runner()
    km = runner.load_kickmix(args.kickmix_build)
    if not hasattr(km.CircuitBuilder, "gf_product"):
        raise SystemExit(f"{km.__file__} has no gf_product; rebuild with "
                         f"scripts/build_kickmix_mr.py")
    base = runner.builder_class(km)
    sys.path.insert(0, str(BUNDLE / "verifiers" / "dqi"))
    import verify_submission_dqi as V

    arms = load_arms(km, runner)
    official = args.degree == 12

    units = unit_costs(km, base, args.degree)
    if official:
        expected = {"builtin": BUILTIN_ANDS + CONTROLLED_ADD, "and54": GF54_ANDS + CONTROLLED_ADD}
        for label, wanted in expected.items():
            got = units["controlled_multiply"][label]["toffoli_like"]
            if got != wanted:
                raise SystemExit(f"{label} controlled multiply is {got} Toffolis, "
                                 f"expected {wanted}")
        # The Itoh-Tsujii chain at 12 bits is three doublings and two folds: five products
        # forward, and the measured block has to be exactly five built-in products.
        inversion = units["inversion"]["builtin"]["toffoli_like"]
        if inversion != 5 * BUILTIN_ANDS:
            raise SystemExit(f"the inversion is not five products: {inversion} Toffolis")
        if units["inversion"]["and54"]["toffoli_like"] != 5 * GF54_ANDS:
            raise SystemExit("the and54 inversion is not five 54-AND products: "
                             f"{units['inversion']['and54']['toffoli_like']} Toffolis")

    functions = function_check(km, base, args.degree, args.checks, 20261029)
    problems = check_function(functions)
    if problems:
        raise SystemExit("the native 54-AND product is wrong, refusing to price it: "
                         + "; ".join(problems))

    record = {
        "engine": "kickmix",
        "kickmix": str(Path(km.__file__).resolve()),
        "kickmix_sha256": hashlib.sha256(Path(km.__file__).read_bytes()).hexdigest(),
        "kickmix_role": "local rebuild with MR (scripts/build_kickmix_mr.py); not the pinned "
                        "competition binary and not eligible for a receipt",
        "instance": {"m": args.m, "n": args.n, "degree": args.degree,
                     "shots": args.shots, "seed": 20261028},
        "subject": "the 54-AND GF(2^12) multiply emitted natively by gen_gf54_mul, selected "
                   "through builder.gf_product = 'and54'",
        "unit_cost": units,
        "function_check": functions,
    }

    if not args.skip_circuits:
        shim_builtin = runner.shim_for(km, native_builder(base, "karatsuba"))
        shim_and54 = runner.shim_for(km, native_builder(base, "and54"))
        shim_forney = runner.shim_for(km, forney_builder(base))
        shim_division = runner.shim_for(km, division_builder(base))
        original = arms.DR.km
        try:
            spec = V.ProblemSpecDQI.benchmark_instance(
                m=args.m, n=args.n, degree=args.degree, num_shots=args.shots)
            weights = V.optimal_dqi_weights(spec.m, spec.max_errors, spec.degree, spec.r) ** 2
            tables = V.FieldTables(km.GF2Field(spec.degree))
            rng = np.random.default_rng(20261028)
            syndromes_in, mbuc_in, _ = V.sample_shots(spec, tables, rng, args.shots, weights)
            reference_inputs = V.to_bits(syndromes_in, args.degree)

            circuits = {}
            for label, shim in (("reference_builtin", shim_builtin),
                                ("reference_forney_and54", shim_forney),
                                ("reference_division_and54", shim_division),
                                ("reference_and54", shim_and54)):
                arms.DR.km = shim
                circuit, syn, mbuc = build_reference(km, arms, shim, args.n, args.degree,
                                                     args.m)
                out = simulate(km, circuit, syn, mbuc, syndromes_in, mbuc_in,
                               args.degree, args.shots)
                circuits[label] = {
                    "qubits": circuit.num_qubits,
                    "toffoli_per_shot": out["toffoli_per_shot"],
                    "ccx_per_shot": out["ccx_per_shot"],
                    "mean_toffoli_like": float(np.mean(out["toffoli_per_shot"])),
                    "junk_clean": bool(not out["junk"].any()),
                    "syndromes_restored": bool(np.array_equal(
                        out["syndromes"], reference_inputs)),
                    "_out": out,
                }

            reference = circuits["reference_builtin"]["_out"]
            for label, shim in (("arm_builtin", shim_builtin),
                                ("arm_forney_and54", shim_forney),
                                ("arm_division_and54", shim_division),
                                ("arm_and54", shim_and54)):
                arms.DR.km = shim
                circuit, syn, mbuc = build_arm(km, arms, shim, SIX_LEVERS, args.n,
                                               args.degree, args.m)
                out = simulate(km, circuit, syn, mbuc, syndromes_in, mbuc_in,
                               args.degree, args.shots)
                circuits[label] = {
                    "qubits": circuit.num_qubits,
                    "toffoli_per_shot": out["toffoli_per_shot"],
                    "ccx_per_shot": out["ccx_per_shot"],
                    "mean_toffoli_like": float(np.mean(out["toffoli_per_shot"])),
                    "correct": is_correct(out, reference, reference_inputs),
                    "_out": out,
                }
        finally:
            arms.DR.km = original

        reference_mean = circuits["reference_builtin"]["mean_toffoli_like"]
        reference_and54 = circuits["reference_and54"]["mean_toffoli_like"]
        for row in circuits.values():
            row.pop("_out", None)
            row["ratio_vs_reference"] = (
                reference_mean / row["mean_toffoli_like"] if row["mean_toffoli_like"] else None)

        # Every product call removes exactly nine Toffolis, controlled or not, so the
        # two circuits' executed CCX difference counts executed calls without an
        # ablation. Differencing two correct circuits is the only way to price the
        # multiply: deleting it moves the state and the predicates with it.
        reference_calls = (np.array(circuits["reference_builtin"]["ccx_per_shot"])
                           - np.array(circuits["reference_and54"]["ccx_per_shot"]))
        arm_calls = (np.array(circuits["arm_builtin"]["ccx_per_shot"])
                     - np.array(circuits["arm_and54"]["ccx_per_shot"]))
        per_call = BUILTIN_ANDS - GF54_ANDS
        for name, delta in (("reference", reference_calls), ("arm", arm_calls)):
            if int(delta.min()) % per_call:
                raise SystemExit(f"{name}: the CCX difference is not a multiple of "
                                 f"{per_call}: {sorted(set(delta.tolist()))}")
        # A Forney position runs five products, so one live position is 5 * 9 Toffolis. If
        # the reference's per-shot difference moves in steps of that, the steps are the
        # inversion and the rest of the difference is the quotient sweep.
        per_position = 5 * per_call
        steps = np.diff(np.sort(np.unique(reference_calls)))
        # Price the Forney block on its own: the same reference with the 54-AND product
        # inside the inversion entry points only. Both circuits are correct and identical
        # elsewhere, so their CCX difference is exactly the executed inversion products.
        forney_delta = (np.array(circuits["reference_builtin"]["ccx_per_shot"])
                        - np.array(circuits["reference_forney_and54"]["ccx_per_shot"]))
        if int(forney_delta.min()) % per_call:
            raise SystemExit(f"forney: the CCX difference is not a multiple of {per_call}: "
                             f"{sorted(set(forney_delta.tolist()))}")
        forney_calls = forney_delta // per_call
        if not circuits["reference_forney_and54"]["syndromes_restored"] \
                or not circuits["reference_forney_and54"]["junk_clean"]:
            raise SystemExit("the Forney-only reference is not correct; refusing to price it")
        forney_saved = (reference_mean
                        - circuits["reference_forney_and54"]["mean_toffoli_like"])
        total_saved = reference_mean - reference_and54
        # The same isolation for the division (change of basis and quotient sweep) at both
        # levels, and for the arm's gated Forney block. Each pair of correct circuits
        # differs only in one entry point's products, so the CCX difference is that
        # block's executed product count and the Toffoli difference is its saving.
        def isolate(a: str, b: str, products_per_call: int) -> dict:
            delta = (np.array(circuits[a]["ccx_per_shot"])
                     - np.array(circuits[b]["ccx_per_shot"]))
            if int(delta.min()) % per_call:
                raise SystemExit(f"{a} vs {b}: CCX difference is not a multiple of "
                                 f"{per_call}: {sorted(set(delta.tolist()))}")
            calls = delta / per_call
            saved = (circuits[a]["mean_toffoli_like"]
                     - circuits[b]["mean_toffoli_like"])
            if not circuits[b].get("junk_clean") or not circuits[b].get(
                    "syndromes_restored"):
                if not circuits[b].get("correct"):
                    raise SystemExit(f"{b} is not correct; refusing to price it")
            return {
                "mean_toffoli_like": circuits[b]["mean_toffoli_like"],
                "qubits": circuits[b]["qubits"],
                "mean_executed_products": float(np.mean(calls)),
                "mean_executed_calls": float(np.mean(calls) / products_per_call),
                "toffoli_saved_per_shot": saved,
                "check_nine_per_product": bool(
                    abs(float(np.mean(calls)) * per_call - saved) < 1e-6),
            }

        division_reference = isolate("reference_builtin", "reference_division_and54", 6)
        division_arm = isolate("arm_builtin", "arm_division_and54", 6)
        inversion_arm = isolate("arm_builtin", "arm_forney_and54", 5)
        uncontrolled_arm = (float(inversion_arm["mean_executed_products"])
                            + float(division_arm["mean_executed_products"]))
        controlled_calls = (float(np.mean(arm_calls / per_call)) - uncontrolled_arm)
        residual = (circuits["arm_and54"]["mean_toffoli_like"]
                    - controlled_calls * (GF54_ANDS + CONTROLLED_ADD)
                    - uncontrolled_arm * GF54_ANDS)
        # Product sites in the reference's Forney step, from the circuit's own structure:
        # one inversion per position, five products in the inversion.
        forney_positions = min((1 << args.degree) - 1, args.m)
        inversion_calls = 5 * forney_positions
        record.update({
            "reference": {
                "builtin": {k: v for k, v in circuits["reference_builtin"].items()},
                "and54": {k: v for k, v in circuits["reference_and54"].items()},
                "executed_product_calls_per_shot": (reference_calls // per_call).tolist(),
                "mean_executed_product_calls": float(np.mean(reference_calls / per_call)),
                "ccx_difference_steps": steps.tolist(),
                "ccx_difference_is_quantised_to_one_forney_position": bool(
                    np.all(steps % per_position == 0)),
                "toffoli_saved_per_shot": reference_mean - reference_and54,
                "saving_percent": 100 * (1 - reference_and54 / reference_mean),
                "recorded_t_mean": REFERENCE_T_MEAN,
            },
            "arm": {
                "builtin": circuits["arm_builtin"],
                "and54": circuits["arm_and54"],
                "executed_product_calls_per_shot": (arm_calls // per_call).tolist(),
                "mean_executed_product_calls": float(np.mean(arm_calls / per_call)),
                "toffoli_saved_per_shot": (circuits["arm_builtin"]["mean_toffoli_like"]
                                           - circuits["arm_and54"]["mean_toffoli_like"]),
                "recorded_builtin_t_mean": ARM_BUILTIN_T_MEAN,
                "recorded_python_emitter_t_mean": ARM_PYTHON_EMITTER_T_MEAN,
            },
            "isolated_blocks": {
                "method": "each figure is the difference between two correct circuits "
                          "that differ only in one entry point's product policy; the "
                          "executed product count is the CCX difference over 9, and a "
                          "division scaffold is six products, an inversion five",
                "reference": {
                    "forney_inversion": {
                        "toffoli_saved_per_shot": forney_saved,
                        "percent_of_reference": 100 * forney_saved / reference_mean,
                        "percent_of_total_saving": (100 * forney_saved / total_saved
                                                    if total_saved else None),
                    },
                    "division_and_sweep": {**division_reference,
                                           "percent_of_reference": 100 * division_reference[
                                               "toffoli_saved_per_shot"] / reference_mean,
                                           "percent_of_total_saving": (
                                               100 * division_reference[
                                                   "toffoli_saved_per_shot"] / total_saved
                                               if total_saved else None)},
                },
                "arm": {
                    "forney_inversion": inversion_arm,
                    "division_and_sweep": division_arm,
                },
                "arm_decomposition": {
                    "note": "three measured terms, not two: only the ixor calls pay the "
                            "12-Toffoli controlled add, while the inversion's and the "
                            "division's products are 54 ANDs each with no add",
                    "controlled_multiplies": controlled_calls,
                    "uncontrolled_products": (float(inversion_arm[
                        "mean_executed_products"])
                        + float(division_arm["mean_executed_products"])),
                    "residual_non_product_toffoli": residual,
                    "residual_ratio_vs_target": (residual / TARGET_T_MEAN
                                                 if args.degree == 12 else None),
                    "check_terms_sum_to_arm": bool(abs(
                        residual
                        + controlled_calls * (GF54_ANDS + CONTROLLED_ADD)
                        + (float(inversion_arm["mean_executed_products"])
                           + float(division_arm["mean_executed_products"])) * GF54_ANDS
                        - circuits["arm_and54"]["mean_toffoli_like"]) < 1e-6),
                },
                "note": "the arm's residual is what an EEA/predicate plan has to attack; "
                        "the two isolated blocks are the parts of the field arithmetic "
                        "this policy also reaches",
            },
            "forney_inversion": {
                "positions": forney_positions,
                "products_per_position": 5,
                "product_sites": inversion_calls,
                "static_toffoli_saved": inversion_calls * per_call,
                "unit_cost_builtin": units["inversion"]["builtin"]["toffoli_like"],
                "unit_cost_and54": units["inversion"]["and54"]["toffoli_like"],
                "isolated": {
                    "method": "the same reference with builder.gf_product = 'and54' "
                              "around init_gf2_inverse_with_scaffold and "
                              "gf2_phase_by_product only; identical elsewhere",
                    "mean_toffoli_like": circuits["reference_forney_and54"][
                        "mean_toffoli_like"],
                    "qubits": circuits["reference_forney_and54"]["qubits"],
                    "executed_product_calls_per_shot": forney_calls.tolist(),
                    "mean_executed_product_calls": float(np.mean(forney_calls)),
                    "mean_executed_positions": float(np.mean(forney_calls) / 5),
                    "toffoli_saved_per_shot": forney_saved,
                    "percent_of_reference": 100 * forney_saved / reference_mean,
                    # At small degrees both algorithms have the same base case, so the
                    # arms coincide and the share is undefined rather than zero.
                    "percent_of_total_saving": (100 * forney_saved / total_saved
                                                if total_saved else None),
                    "saved_per_executed_position": per_position,
                    "check_toffoli_saved_is_nine_per_product": bool(
                        abs(float(np.mean(forney_calls)) * per_call - forney_saved) < 1e-6),
                },
                "everything_else_toffoli_saved_per_shot": total_saved - forney_saved,
                "everything_else_percent_of_total_saving": (
                    100 * (1 - forney_saved / total_saved) if total_saved else None),
                "note": "the reference's inversion pair costs five products forward and "
                        "measures the same product back, so only the forward five are "
                        "priced; the static site count assumes every position executes and "
                        "the isolated arm measures how many actually do",
            },
        })
        # Five different comparisons live in these two rows, and quoting one as if it
        # were another has already produced a review objection. Each is named with its
        # baseline here so a reader cannot pick the wrong pair.
        def q2t(row: dict) -> float:
            return float(row["qubits"]) ** 2 * row["mean_toffoli_like"]

        record["comparisons"] = {
            "note": "every row names its baseline. These are T-count ratios, not score "
                    "ratios: the score is R(eps_plus) * Q^2 * T, and R needs the official "
                    "sample. The headline T-count gain is the arm against the unchanged "
                    "reference; the same-policy ratio isolates the six levers under the "
                    "new field arithmetic",
            "multiply_effect_on_reference_percent": 100 * (
                1 - circuits["reference_and54"]["mean_toffoli_like"]
                / circuits["reference_builtin"]["mean_toffoli_like"]),
            "multiply_effect_on_arm_percent": 100 * (
                1 - circuits["arm_and54"]["mean_toffoli_like"]
                / circuits["arm_builtin"]["mean_toffoli_like"]),
            "arm_vs_unchanged_reference": (
                circuits["reference_builtin"]["mean_toffoli_like"]
                / circuits["arm_and54"]["mean_toffoli_like"]),
            "arm_vs_same_policy_reference": (
                circuits["reference_and54"]["mean_toffoli_like"]
                / circuits["arm_and54"]["mean_toffoli_like"]),
            "arm_q2t_reduction_vs_builtin_arm_percent": 100 * (
                1 - q2t(circuits["arm_and54"]) / q2t(circuits["arm_builtin"])),
            "arm_q2t_builtin": q2t(circuits["arm_builtin"]),
            "arm_q2t_and54": q2t(circuits["arm_and54"]),
        }
        record["pinned_instance"] = (args.degree, args.n, args.m) == (12, 70, 4095)

    args.record.parent.mkdir(parents=True, exist_ok=True)
    args.record.write_text(json.dumps(record, indent=2) + "\n")

    print(f"kickmix {record['kickmix_role'].split(';')[0]}")
    print(f"native and54 on {sys.platform}, GF(2^{args.degree})")
    for name, rows in units.items():
        print(f"  {name:20s} builtin={rows['builtin']['toffoli_like']:5d} "
              f"and54={rows['and54']['toffoli_like']:5d} "
              f"(workspace {rows['builtin']['workspace']} -> {rows['and54']['workspace']})")
    print("  function check: " + ", ".join(
        f"{name}={row['value_mismatches']} bad/{row['samples']}"
        for name, row in ((k, v['native_and54']) for k, v in functions.items())))
    if "reference" in record:
        ref = record["reference"]
        arm = record["arm"]
        print(f"\n  reference  {ref['builtin']['mean_toffoli_like']:.1f} -> "
              f"{ref['and54']['mean_toffoli_like']:.1f} per shot "
              f"({ref['saving_percent']:.2f}%, Q {ref['builtin']['qubits']} -> "
              f"{ref['and54']['qubits']})")
        print(f"  arm        {arm['builtin']['mean_toffoli_like']:.1f} -> "
              f"{arm['and54']['mean_toffoli_like']:.1f} per shot "
              f"(ratio {arm['and54']['ratio_vs_reference']:.3f}x against "
              f"{arm['builtin']['ratio_vs_reference']:.3f}x)")
        fny = record["forney_inversion"]["isolated"]
        share = (f"{fny['percent_of_total_saving']:.1f}% of the saving"
                 if fny["percent_of_total_saving"] is not None else "no measurable saving")
        cmp = record["comparisons"]
        print(f"  comparisons multiply: reference -{cmp['multiply_effect_on_reference_percent']:.2f}%, "
              f"arm -{cmp['multiply_effect_on_arm_percent']:.2f}%; arm vs unchanged "
              f"reference {cmp['arm_vs_unchanged_reference']:.3f}x, vs same-policy "
              f"reference {cmp['arm_vs_same_policy_reference']:.3f}x; arm Q^2T "
              f"-{cmp['arm_q2t_reduction_vs_builtin_arm_percent']:.2f}%")
        print(f"  Forney     {record['forney_inversion']['product_sites']} product sites, "
              f"{record['forney_inversion']['static_toffoli_saved']} static Toffolis; "
              f"isolated {fny['mean_executed_product_calls']:.1f} executed products "
              f"({fny['mean_executed_positions']:.1f} positions) = "
              f"{fny['toffoli_saved_per_shot']:.0f} Toffolis, "
              f"{fny['percent_of_reference']:.2f}% of the reference and {share}")
    print(f"\nrecord: {args.record}")
    return 0


