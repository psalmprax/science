class ImprovementLevel(Enum):
    """The 4 levels a self-improvement proposal may target."""

    LEVEL_1_PARAMETER = "parameter"
    LEVEL_2_STRATEGY = "strategy"
    LEVEL_3_PIPELINE = "pipeline"
    LEVEL_4_SCIENTIFIC_METHOD = "scientific_method"


@dataclass(frozen=True)
class ModificationProposal:
    """A proposed modification generated by the improvement agent."""

    proposal_id: str
    level: ImprovementLevel
    target_component: str
    modifications: dict[str, Any]
    hypothesis: str
    rationale: str
    author: str
    timestamp: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    # The two flags the constitutional auditor reads directly. Both default
    # to False: a proposal that does not say it touches benchmark data is
    # taken at its word, and the audit records what was claimed.
    modifies_benchmark_data: bool = False
    retrospective_criterion_change: bool = False

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.proposal_id,
            "level": self.level.value,
            "target_component": self.target_component,
            "modifications": dict(self.modifications),
            "hypothesis": self.hypothesis,
            "rationale": self.rationale,
            "author": self.author,
            "timestamp": self.timestamp,
            "modifies_benchmark_data": self.modifies_benchmark_data,
            "retrospective_criterion_change": self.retrospective_criterion_change,
        }


@dataclass(frozen=True)
class DiagnosticSignal:
    """Diagnostic generated by FailureDetector from completed run history."""

    signal_type: str
    severity: str
    affected_component: str
    description: str
    evidence_metrics: dict[str, float]
    suggested_level: ImprovementLevel


class FailureDetector:
    """Derives diagnostics from completed run histories.

    Every rule here is a threshold on a quantity the run history already
    records. None of them proposes a change; they name a symptom and the
    level at which a fix would have to live.
    """

    @staticmethod
    def detect_weaknesses(run_histories: list[dict[str, Any]]) -> list[DiagnosticSignal]:
        signals: list[DiagnosticSignal] = []
        total_runs = len(run_histories)
        if total_runs == 0:
            return signals

        # Rule 1: too many generated candidates carry transcendental
        # arguments the grammar cannot resolve. Points at the generator,
        # not at the parameters, so Level 3.
        total_candidates = 0
        transcendental_unresolved_count = 0
        for r in run_histories:
            cands = r.get("candidates", [])
            total_candidates += len(cands)
            for c in cands:
                if ("transcendental" in c.get("reason_chain", "").lower()
                        or c.get("dim_status") == "UNRESOLVED"):
                    transcendental_unresolved_count += 1
        if total_candidates > 0:
            unresolved_ratio = transcendental_unresolved_count / total_candidates
            if unresolved_ratio > 0.2:
                signals.append(DiagnosticSignal(
                    signal_type="HIGH_UNRESOLVED_TRANSCENDENTAL_RATE",
                    severity="HIGH",
                    affected_component="grammar_generator",
                    description=f"{unresolved_ratio:.1%} of generated candidates have "
                                f"unresolvable transcendental arguments.",
                    evidence_metrics={"unresolved_ratio": unresolved_ratio},
                    suggested_level=ImprovementLevel.LEVEL_3_PIPELINE,
                ))

        # Rule 2: an excellent in-sample fit that does not survive near-OOD.
        # The scalar-fit trap, seen from the history rather than from a
        # single problem, so it is Level 4 -- a method problem, not a
        # parameter one.
        ood_divergences = 0
        for r in run_histories:
            for c in r.get("candidates", []):
                train_mse = c.get("train_mse", 0.0)
                near_ood_mse = c.get("near_ood_mse", 0.0)
                if train_mse < 0.1 and near_ood_mse > 100.0:
                    ood_divergences += 1
        if ood_divergences > 0:
            signals.append(DiagnosticSignal(
                signal_type="SCALAR_FIT_NEAR_OOD_DIVERGENCE",
                severity="CRITICAL",
                affected_component="selector",
                description=f"{ood_divergences} candidates exhibit extreme scalar "
                            f"in-sample fit with near-OOD divergence.",
                evidence_metrics={"divergence_count": float(ood_divergences)},
                suggested_level=ImprovementLevel.LEVEL_4_SCIENTIFIC_METHOD,
            ))

        # Rule 3: a coupling residual ratio that has fallen far enough below
        # its own threshold that the separability gate is probably
        # misfiring. Level 1: the fix is the threshold.
        for r in run_histories:
            coupling_ratio = r.get("coupling_residual_ratio")
            thresh = r.get("coupling_residual_threshold", 0.15)
            if coupling_ratio is not None and coupling_ratio > 0.06 and coupling_ratio <= thresh:
                signals.append(DiagnosticSignal(
                    signal_type="PROVISIONAL_COUPLING_THRESHOLD_MISS",
                    severity="MEDIUM",
                    affected_component="separability_gate",
                    description=f"Coupling residual ratio ({coupling_ratio:.3f}) fell below "
                                f"threshold ({thresh:.3f}), risking missed interaction.",
                    evidence_metrics={"coupling_ratio": coupling_ratio, "threshold": thresh},
                    suggested_level=ImprovementLevel.LEVEL_1_PARAMETER,
                ))

        return signals


@dataclass(frozen=True)
class GatekeeperDecision:
    """The gatekeeper's ruling on one proposal, with its own provenance."""

    proposal_id: str
    accepted: bool
    status: str
    constitutional_verdict: ConstitutionalVerdict
    target_metric_deltas: dict[str, float] = field(default_factory=dict)
    regression_summary: str = ""
    provenance_hash: str = ""
    timestamp: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "proposal_id": self.proposal_id,
            "accepted": self.accepted,
            "status": self.status,
            "constitutional_verdict": self.constitutional_verdict.to_dict(),
            "target_metric_deltas": dict(self.target_metric_deltas),
            "regression_summary": self.regression_summary,
            "provenance_hash": self.provenance_hash,
            "timestamp": self.timestamp,
        }


class IndependentGatekeeper:
    """Applies the constitution and the regression gate, and nothing else.

    The gatekeeper is not permitted to accept a proposal on its own
    judgement. It runs the constitutional audit, and accepts only if the
    verdict is compliant *and* the frozen regression suite passed. There is
    no override path, which is the point: an improvement agent that can
    talk its way past its own gate is not governed.
    """

    @staticmethod
    def evaluate_and_decide(
        proposal: ModificationProposal,
        benchmark_results: dict[str, Any] | None = None,
        regression_passed: bool = True,
    ) -> GatekeeperDecision:
        auditor = ConstitutionalAuditor()
        verdict = auditor.audit(
            proposal_dict=proposal.to_dict(),
            benchmark_results=benchmark_results,
            regression_passed=regression_passed,
            provenance_trace={
                "author": proposal.author,
                "timestamp": proposal.timestamp,
                "history_logging_active": True,
            },
        )

        # target_metric_improved is reserved. The gate currently decides on
        # constitution plus regression only, and this stays False so the
        # field is visibly not being used as a third opinion. The original
        # computed this local and never read it, and it is kept for fidelity
        # rather than removed -- its deadness is the point: the third input
        # the decision record carries is not yet wired to anything.
        metric_deltas: dict[str, float] = {}
        target_metric_improved = False  # noqa: F841 - reserved, see above

        accepted = verdict.compliant and regression_passed
        status = "PROMOTED" if accepted else "DISCARDED"

        provenance_payload = json.dumps({
            "proposal_id": proposal.proposal_id,
            "status": status,
            "constitutional_sha": verdict.sha256,
            "timestamp": proposal.timestamp,
        }, sort_keys=True).encode("utf-8")

        return GatekeeperDecision(
            proposal_id=proposal.proposal_id,
            accepted=accepted,
            status=status,
            constitutional_verdict=verdict,
            target_metric_deltas=metric_deltas,
            regression_summary=("PASS: All frozen benchmarks intact" if regression_passed
                                else "FAIL: Regression detected"),
            provenance_hash=hashlib.sha256(provenance_payload).hexdigest(),
            timestamp=datetime.now(timezone.utc).isoformat(),
        )


class ImprovementLedger:
    """Append-only history of every gatekeeper decision.

    Retaining failures is a constitutional requirement (INV-8), not a
    convenience: an improvement process that discards its rejected attempts
    cannot learn which directions have already been tried.
    """

    def __init__(self, records: list[dict[str, Any]] | None = None):
        self.records: list[dict[str, Any]] = list(records) if records else []

    def record_decision(self, proposal: ModificationProposal,
                        decision: GatekeeperDecision) -> None:
        self.records.append({
            "proposal": proposal.to_dict(),
            "decision": decision.to_dict(),
            "entry_hash": decision.provenance_hash,
        })

    def to_list(self) -> list[dict[str, Any]]:
        return list(self.records)


