"""Roberts–Chebyshev cognates of a four-bar (blueprint §5.8).

Roberts' theorem: the coupler curve of a four-bar is generated by three
different four-bars ("cognates"), whose three ground pivots form a triangle
similar to the coupler triangle. Chebyshev and Cayley gave the graphical
construction; this module states it algebraically and, more importantly, checks
it against the property it is famous for.

Derivation. Write the coupler point as ``P = A + w e^{i theta3}`` with ``w`` a
complex constant in the coupler frame (``|w| = AP``), the coupler length as
``beta`` (so ``P - B = (w - beta) e^{i theta3}``, ``|w - beta| = BP``), the crank
and output lengths as ``alpha`` and ``gamma``, and the fixed link as ``g``. The
loop closure ``alpha e^{i theta2} + beta e^{i theta3} = g + gamma e^{i theta4}``
then gives, for the two cognates beside the original,

* shared fourth ground pivot ``C0 = A0 + (w / beta) g`` — by construction a
  constant, which is exactly what makes the cognates four-bars and not
  fictitious linkages;
* cognate "left": crank ``w e^{i theta3}``, coupler ``(w alpha / beta) e^{i
  theta2}``, output ``(w gamma / beta) e^{i theta4}``, coupler point on that
  coupler at ``alpha`` from the crank end;
* cognate "right": crank ``(w - beta) e^{i theta3}``, coupler ``(gamma (beta -
  w) / beta) e^{i theta4}``, output ``(alpha (beta - w) / beta) e^{i theta2}``,
  coupler point on that coupler at ``gamma`` from the crank end.

Substituting any one of those into its own loop equation reproduces the original
closure multiplied by a constant, which is why all three coupler points coincide
at ``P`` at every instant and therefore trace the same curve. Each cognate line
length is a scaled version of an original length, so the cognates are
dimensionally dissimilar — the point of the theorem.

The check is deliberately not "the formula reproduces itself": for every sampled
input angle the cognate is re-solved *independently* with its own
:class:`~mmlm_matter_001.kinematics.fourbar.FourBar` closed form, driven by the
crank angle the assembly implies, and the coupler point it produces is compared
with the original's. The focal pivot's motion and the ordered curve distance are
reported too, so a construction that closes a loop but drifts from the curve
cannot pass quietly.
"""

from __future__ import annotations

import math
from collections.abc import Sequence
from dataclasses import dataclass

from mmlm_matter_001.kinematics.fourbar import (
    BranchError,
    FourBar,
    MechanismError,
    Pose,
    angle_difference_deg,
    branch_of_theta3,
    wrap_deg,
)
from mmlm_matter_001.kinematics.path_metric import discrete_frechet

Point = tuple[float, float]
Complex = complex

#: Numerical-equality tolerance of the construction itself. Not a protocol
#: threshold: a gate passes the task's declared tolerance to
#: :func:`check_cognates`.
COGNATE_TOLERANCE_MM = 1e-6

COGNATE_NAMES = ("original", "left", "right")

#: Machine-readable reasons a cognate check can fail.
COGNATE_REASONS = frozenset({
    "unreachable_input",
    "cognate_not_assemblable",
    "focal_pivot_moves",
    "coupler_point_gap",
    "curve_gap",
    "curve_set_gap",
    "cognate_angle_gap",
})

_ZERO = 1e-12

#: How closely a constructed coupler direction must match a cognate's own root.
ANGLE_MATCH_DEG = 1e-6


def _complex(point: Point) -> Complex:
    return complex(point[0], point[1])


def _point(value: Complex) -> Point:
    return (value.real, value.imag)


def _unit(angle_rad: float) -> Complex:
    return complex(math.cos(angle_rad), math.sin(angle_rad))


def symmetric_hausdorff(first: Sequence[Point], second: Sequence[Point]) -> float:
    """Largest distance from any point of either set to the nearest point of the other.

    Ordered agreement (Fréchet) is the stronger statement at matched inputs. This
    is the set-level statement, which is what "the same curve" means when each
    cognate is driven independently and its parameterization therefore differs:
    two curves can be pointwise identical yet be sampled differently.
    """
    if not first or not second:
        raise MechanismError("a Hausdorff distance needs two non-empty point sets")
    forward = max(min(math.dist(point, other) for other in second) for point in first)
    backward = max(min(math.dist(point, other) for other in first) for point in second)
    return max(forward, backward)


def _solve_either(mechanism: FourBar, theta2_deg: float, branch: str) -> Pose:
    """Solve on `branch`, falling back to the other only where the two meet.

    :class:`~mmlm_matter_001.kinematics.fourbar.BranchError` is raised only when
    the requested assembly does not exist, which happens at a tangency where the
    one available pose *is* the other branch. An unreachable input still raises.
    """
    if branch not in ("open", "crossed"):
        branch = "open"
    try:
        return mechanism.solve(theta2_deg, branch=branch)
    except BranchError:
        return mechanism.solve(
            theta2_deg, branch="crossed" if branch == "open" else "open")


@dataclass(frozen=True, slots=True)
class Cognate:
    """One of the three four-bars, expressed in the canonical frame.

    The mechanism keeps the convention of
    :class:`~mmlm_matter_001.kinematics.fourbar.FourBar` — ground pivot at the
    origin, ground link along ``+x`` — so it can be solved by the same closed
    form. :attr:`ground_origin_mm` and :attr:`ground_angle_deg` map that frame
    back to the reference frame the original mechanism is drawn in.
    """

    name: str
    mechanism: FourBar
    ground_origin_mm: Point
    ground_angle_deg: float
    ground_pivots_mm: tuple[Point, Point]
    coupler_point_local_mm: Point
    input_angle_deg: float
    branch: str
    inversion: str
    grashof: bool

    def to_world(self, point: Point) -> Point:
        angle = math.radians(self.ground_angle_deg)
        cosine, sine = math.cos(angle), math.sin(angle)
        return (
            self.ground_origin_mm[0] + point[0] * cosine - point[1] * sine,
            self.ground_origin_mm[1] + point[0] * sine + point[1] * cosine,
        )

    def from_world(self, point: Point) -> Point:
        angle = math.radians(self.ground_angle_deg)
        cosine, sine = math.cos(angle), math.sin(angle)
        x = point[0] - self.ground_origin_mm[0]
        y = point[1] - self.ground_origin_mm[1]
        return (x * cosine + y * sine, -x * sine + y * cosine)

    def nearest_coupler_point(
        self, crank_vector: Complex, coupler_vector: Complex
    ) -> tuple[Point, float]:
        """The closest assembly, and how far its coupler direction is from the constructed one.

        Returning the nearest root instead of raising lets the checker report a
        measured gap for a cognate whose constructed configuration does not exist,
        rather than only a reason. The angular shortfall is reported separately, so
        a reader can tell "wrong assembly" from "wrong direction".
        """
        angle = math.radians(self.ground_angle_deg)
        theta2_local = wrap_deg(
            math.degrees(math.atan2(crank_vector.imag, crank_vector.real) - angle))
        expected_coupler = wrap_deg(
            math.degrees(math.atan2(coupler_vector.imag, coupler_vector.real) - angle))
        candidates = self.mechanism.poses(theta2_local)
        if not candidates:
            raise MechanismError(
                f"cognate {self.name!r} has no assembly at input "
                f"{theta2_local:.6g} deg")
        best = min(
            candidates,
            key=lambda pose: abs(
                angle_difference_deg(expected_coupler, pose.theta3_deg)),
        )
        return (
            self.to_world(best.coupler_point_mm),
            abs(angle_difference_deg(expected_coupler, best.theta3_deg)),
        )

    def world_coupler_point(
        self, crank_vector: Complex, coupler_vector: Complex
    ) -> Point:
        """Solve this cognate from its own links at the assembled configuration.

        Only the crank and coupler *directions* come from the assembly. The pose
        is a root of this cognate's own closed form — selected by the assembled
        coupler direction rather than by the branch label, because the two roots
        can share a label — so agreement is evidence, not an identity.
        """
        world, gap = self.nearest_coupler_point(crank_vector, coupler_vector)
        if gap > ANGLE_MATCH_DEG:
            raise MechanismError(
                f"cognate {self.name!r} has no assembly with its constructed coupler "
                f"direction: the nearest is {gap:.6g} deg away")
        return world

    def record(self) -> dict[str, object]:
        return {
            "name": self.name,
            "link_lengths_mm": self.mechanism.link_lengths_mm,
            "coupler_point_local_mm": list(self.coupler_point_local_mm),
            "ground_origin_mm": list(self.ground_origin_mm),
            "ground_angle_deg": self.ground_angle_deg,
            "ground_pivots_mm": [list(point) for point in self.ground_pivots_mm],
            "input_angle_deg": self.input_angle_deg,
            "branch": self.branch,
            "inversion": self.inversion,
            "grashof": self.grashof,
        }


@dataclass(frozen=True, slots=True)
class _Assembly:
    """The Roberts construction at one pose, in world coordinates."""

    focal: Complex
    left_crank: Complex
    left_coupler: Complex
    right_crank: Complex
    right_coupler: Complex


@dataclass(frozen=True, slots=True)
class RobertsCognates:
    """The original four-bar and its two cognates, built from one reference pose."""

    mechanism: FourBar
    theta2_deg: float
    branch: str
    original: Cognate
    left: Cognate
    right: Cognate
    focal_pivot_mm: Point
    focal_pivots_mm: tuple[Point, Point, Point]
    coupler_triangle_mm: tuple[float, float, float]

    @property
    def all(self) -> tuple[Cognate, ...]:
        return (self.original, self.left, self.right)

    def record(self) -> dict[str, object]:
        return {
            "reference_input_deg": self.theta2_deg,
            "branch": self.branch,
            "focal_pivot_mm": list(self.focal_pivot_mm),
            "focal_pivots_mm": [list(point) for point in self.focal_pivots_mm],
            "coupler_triangle_mm": list(self.coupler_triangle_mm),
            "cognates": {cognate.name: cognate.record() for cognate in self.all},
        }


def _assembly(mechanism: FourBar, pose: Pose) -> _Assembly:
    """The focal pivot and the two cognate crank vectors at one pose."""
    theta3 = math.radians(pose.theta3_deg)
    pivot_a = _complex(pose.pivot_a_mm)
    coupler_point = _complex(pose.coupler_point_mm)
    coupler = complex(mechanism.coupler_mm, 0.0)
    w = (coupler_point - pivot_a) * _unit(-theta3)
    if abs(w) <= _ZERO:
        raise MechanismError(
            "the coupler point coincides with the crank pivot, so there is no "
            "coupler triangle and no cognate")
    if abs(w - coupler) <= _ZERO:
        raise MechanismError(
            "the coupler point coincides with the output pivot, so there is no "
            "coupler triangle and no cognate")
    ground = complex(mechanism.ground_mm, 0.0)
    alpha = complex(mechanism.input_mm, 0.0)
    gamma = complex(mechanism.output_mm, 0.0)
    theta2 = math.radians(pose.theta2_deg)
    theta4 = math.radians(pose.theta4_deg)
    return _Assembly(
        focal=(w / coupler) * ground,
        left_crank=w * _unit(theta3),
        left_coupler=(w * alpha / coupler) * _unit(theta2),
        right_crank=(w - coupler) * _unit(theta3),
        right_coupler=(gamma * (coupler - w) / coupler) * _unit(theta4),
    )


def _build_cognate(
    name: str,
    *,
    crank_pivot: Complex,
    output_pivot: Complex,
    crank_end: Complex,
    coupler_end: Complex,
    coupler_point: Complex,
) -> Cognate:
    ground_vector = output_pivot - crank_pivot
    ground_angle = math.atan2(ground_vector.imag, ground_vector.real)
    crank = crank_end - crank_pivot
    coupler = coupler_end - crank_end
    if abs(crank) <= _ZERO or abs(coupler) <= _ZERO or abs(ground_vector) <= _ZERO:
        raise MechanismError(f"cognate {name!r} has a zero-length link")
    local_point = (coupler_point - crank_end) * _unit(
        -math.atan2(coupler.imag, coupler.real))
    mechanism = FourBar(
        ground_mm=abs(ground_vector),
        input_mm=abs(crank),
        coupler_mm=abs(coupler),
        output_mm=abs(coupler_end - output_pivot),
        coupler_point_mm=(local_point.real, local_point.imag),
    )
    theta2_local = wrap_deg(
        math.degrees(math.atan2(crank.imag, crank.real) - ground_angle))
    theta3_local = wrap_deg(
        math.degrees(math.atan2(coupler.imag, coupler.real) - ground_angle))
    grashof = mechanism.check_grashof()
    return Cognate(
        name=name,
        mechanism=mechanism,
        ground_origin_mm=_point(crank_pivot),
        ground_angle_deg=wrap_deg(math.degrees(ground_angle)),
        ground_pivots_mm=(_point(crank_pivot), _point(output_pivot)),
        coupler_point_local_mm=(local_point.real, local_point.imag),
        input_angle_deg=theta2_local,
        branch=branch_of_theta3(theta3_local),
        inversion=grashof.inversion,
        grashof=grashof.is_grashof,
    )


def roberts_cognates(
    mechanism: FourBar,
    theta2_deg: float | None = None,
    *,
    branch: str = "open",
) -> RobertsCognates:
    """Build the two cognates of `mechanism` from one reference pose.

    ``theta2_deg=None`` takes the first input angle in a 5-degree sweep that
    assembles on `branch`. The reference pose fixes the cognates' dimensions;
    the theorem makes those dimensions pose-independent, and the check verifies
    that on a range that need not contain the reference angle.
    """
    if not isinstance(mechanism, FourBar):
        raise MechanismError(
            f"cognates need a FourBar, got {type(mechanism).__name__}")
    pose = _reference_pose(mechanism, theta2_deg, branch)
    assembly = _assembly(mechanism, pose)

    theta3 = math.radians(pose.theta3_deg)
    ground = complex(mechanism.ground_mm, 0.0)
    beta = complex(mechanism.coupler_mm, 0.0)

    pivot_a = _complex(pose.pivot_a_mm)
    coupler_point = _complex(pose.coupler_point_mm)
    w = (coupler_point - pivot_a) * _unit(-theta3)

    # A0A1 = P - A (the parallelogram), so the left crank is w e^{i theta3}.
    origin = 0j
    left_pivot = assembly.focal
    left_crank_end = assembly.left_crank
    left_coupler_end = left_crank_end + assembly.left_coupler
    # B0B1 = P - B, so the right crank is (w - beta) e^{i theta3}.
    right_origin = ground
    right_crank_end = right_origin + assembly.right_crank
    right_coupler_end = right_crank_end + assembly.right_coupler

    original = Cognate(
        name="original",
        mechanism=mechanism,
        ground_origin_mm=(0.0, 0.0),
        ground_angle_deg=0.0,
        ground_pivots_mm=((0.0, 0.0), _point(ground)),
        coupler_point_local_mm=mechanism.coupler_point_mm,
        input_angle_deg=pose.theta2_deg,
        branch=pose.branch,
        inversion=mechanism.check_grashof().inversion,
        grashof=mechanism.check_grashof().is_grashof,
    )
    left = _build_cognate(
        "left",
        crank_pivot=origin,
        output_pivot=left_pivot,
        crank_end=left_crank_end,
        coupler_end=left_coupler_end,
        coupler_point=coupler_point,
    )
    right = _build_cognate(
        "right",
        crank_pivot=right_origin,
        output_pivot=left_pivot,
        crank_end=right_crank_end,
        coupler_end=right_coupler_end,
        coupler_point=coupler_point,
    )

    cognates = RobertsCognates(
        mechanism=mechanism,
        theta2_deg=pose.theta2_deg,
        branch=branch,
        original=original,
        left=left,
        right=right,
        focal_pivot_mm=_point(left_pivot),
        focal_pivots_mm=((0.0, 0.0), _point(ground), _point(left_pivot)),
        coupler_triangle_mm=(
            mechanism.coupler_mm,
            abs(w - beta),
            abs(w),
        ),
    )
    _require_reference_pose(cognates, pose, assembly)
    return cognates


def _require_reference_pose(
    cognates: RobertsCognates, pose: Pose, assembly: _Assembly
) -> None:
    """Fail loudly when the construction does not reproduce its own reference pose."""
    expected = pose.coupler_point_mm
    for name, cognate, crank, coupler in (
        ("left", cognates.left, assembly.left_crank, assembly.left_coupler),
        ("right", cognates.right, assembly.right_crank, assembly.right_coupler),
    ):
        world = cognate.world_coupler_point(crank, coupler)
        gap = math.dist(world, expected)
        if gap > COGNATE_TOLERANCE_MM:
            raise MechanismError(
                f"cognate {name!r} does not reproduce the reference coupler point: "
                f"off by {gap:.6g} mm")


def check_cognates(
    cognates: RobertsCognates,
    *,
    input_range_deg: tuple[float, float],
    samples: int = 61,
    tolerance_mm: float = COGNATE_TOLERANCE_MM,
    angle_tolerance_deg: float = ANGLE_MATCH_DEG,
) -> CognateCheck:
    """Check the three cognates against the coupler curve they must share.

    The original's curve is produced by the original closed form, each cognate's
    curve by that cognate's own closed form driven by the crank angle the
    Roberts assembly implies. ``tolerance_mm`` is the declared tolerance of the
    claim; every reported gap is measured against it.
    """
    if not isinstance(cognates, RobertsCognates):
        raise MechanismError(
            f"check_cognates needs RobertsCognates, got {type(cognates).__name__}")
    if not math.isfinite(tolerance_mm) or tolerance_mm <= 0.0:
        raise MechanismError(
            f"tolerance_mm must be finite and positive, got {tolerance_mm!r}")
    if not (math.isfinite(angle_tolerance_deg) and angle_tolerance_deg > 0.0):
        raise MechanismError(
            f"angle_tolerance_deg must be finite and positive, got "
            f"{angle_tolerance_deg!r}")
    if samples < 2:
        raise MechanismError(f"samples must be at least 2, got {samples!r}")
    low, high = input_range_deg
    if not (math.isfinite(low) and math.isfinite(high)) or not low < high:
        raise MechanismError(
            f"input_range_deg must be finite and increasing, got {input_range_deg!r}")

    mechanism = cognates.mechanism
    original_points: list[Point] = []
    left_points: list[Point] = []
    right_points: list[Point] = []
    focal_drift = 0.0
    reference_focal = _complex(cognates.focal_pivot_mm)
    gaps = {"left": 0.0, "right": 0.0}
    angle_gaps = {"left": 0.0, "right": 0.0}
    details: list[str] = []
    unreachable = 0
    unassemblable = 0

    for index in range(samples):
        theta2_deg = low + (high - low) * index / (samples - 1)
        try:
            pose = _solve_either(mechanism, theta2_deg, cognates.branch)
        except MechanismError:
            unreachable += 1
            if len(details) < 5:
                details.append(
                    f"input {theta2_deg:.6g} deg: the original has no assembly")
            continue
        assembly = _assembly(mechanism, pose)
        focal_drift = max(focal_drift, abs(assembly.focal - reference_focal))
        point = pose.coupler_point_mm
        left_world = right_world = None
        for name, cognate, crank, coupler in (
            ("left", cognates.left, assembly.left_crank, assembly.left_coupler),
            ("right", cognates.right, assembly.right_crank, assembly.right_coupler),
        ):
            try:
                world, angle_gap = cognate.nearest_coupler_point(crank, coupler)
            except MechanismError as exc:
                unassemblable += 1
                if len(details) < 5:
                    details.append(f"{name} at {theta2_deg:.6g} deg: {exc}")
                continue
            angle_gaps[name] = max(angle_gaps[name], angle_gap)
            gap = math.dist(world, point)
            gaps[name] = max(gaps[name], gap)
            if name == "left":
                left_world = world
            else:
                right_world = world
        if left_world is None or right_world is None:
            continue
        original_points.append(point)
        left_points.append(left_world)
        right_points.append(right_world)

    frechet: dict[str, float] = {}
    hausdorff: dict[str, float] = {}
    if original_points and len(left_points) == len(original_points):
        frechet["left"] = discrete_frechet(original_points, left_points)
        frechet["right"] = discrete_frechet(original_points, right_points)
        hausdorff["left"] = symmetric_hausdorff(original_points, left_points)
        hausdorff["right"] = symmetric_hausdorff(original_points, right_points)

    reasons: list[str] = []
    if unreachable:
        reasons.append("unreachable_input")
    if unassemblable:
        reasons.append("cognate_not_assemblable")
    if focal_drift > tolerance_mm:
        reasons.append("focal_pivot_moves")
    if max(gaps.values(), default=0.0) > tolerance_mm:
        reasons.append("coupler_point_gap")
    if any(value > tolerance_mm for value in frechet.values()):
        reasons.append("curve_gap")
    if any(value > tolerance_mm for value in hausdorff.values()):
        reasons.append("curve_set_gap")
    if max(angle_gaps.values(), default=0.0) > angle_tolerance_deg:
        reasons.append("cognate_angle_gap")

    return CognateCheck(
        passed=not reasons,
        tolerance_mm=tolerance_mm,
        angle_tolerance_deg=angle_tolerance_deg,
        input_range_deg=(low, high),
        samples=samples,
        focal_drift_mm=focal_drift,
        coupler_gap_mm=gaps,
        frechet_mm=frechet,
        hausdorff_mm=hausdorff,
        coupler_angle_gap_deg=angle_gaps,
        inversion={cognate.name: cognate.inversion for cognate in cognates.all},
        grashof={cognate.name: cognate.grashof for cognate in cognates.all},
        focal_pivot_mm=cognates.focal_pivot_mm,
        reasons=tuple(reasons),
        details=tuple(details),
    )


def _reference_pose(mechanism: FourBar, theta2_deg: float | None, branch: str) -> Pose:
    if theta2_deg is not None:
        return _solve_either(mechanism, theta2_deg, branch)
    for index in range(72):
        candidate = 5.0 * index
        try:
            return _solve_either(mechanism, candidate, branch)
        except MechanismError:
            continue
    raise MechanismError(
        "no reference pose assembles on either branch in the 5-degree sweep from "
        "0 deg; pass theta2_deg explicitly")


