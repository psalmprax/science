"""Multiplication in GF(2^12) with 42 products, built from the tower over GF(8), and checked exactly.

Status: experimental

**Why this exists.** MMLM-POC-001 measures a search against a "published 51-product incumbent" of
which the repository holds no copy (``field_tensor_search.load_published_51_reference`` returns
zeros), and its target was 50 products. The literature's bound is lower. The survey of Ballet,
Pieltant, Rambaud, Randriambololona, Rolland and Chaumine (Russian Math. Surveys 76:1, 2021;
arXiv:1906.07456), Table 2, gives the best known upper bound on the symmetric bilinear complexity
of multiplication in GF(2^12) over GF(2) as **42**. So 50 products would not be new, and a search
is measured against 42.

**The construction** is the classical one behind that number, written out and verified here:

* GF(2^12) has degree 4 over GF(8). A product of two polynomials of degree at most 3 over GF(8)
  has 7 coefficients, so it is fixed by its values at 7 points, and GF(8) has 8. That is 7
  multiplications in GF(8) (evaluation and interpolation: the bilinear complexity of a degree-4
  extension of GF(8) is 2*4 - 1 = 7).
* A multiplication in GF(8) is a product of two 3-term polynomials over GF(2), which takes 6
  products of bits (the Karatsuba-like formula for three terms), then a reduction, which is linear.
* 7 * 6 = 42 products of one linear form of the first factor's bits with the same form of the
  second's: the decomposition is symmetric (``U == V``).

Everything is computed in the repository's own representation of the field
(``u^12 + u^6 + u^4 + u + 1``): the copy of GF(8) is generated by ``u^585``, an element of order
7; the output weights are found by solving the linear system exactly over GF(2)
(``field_tensor_search.solve_gf2_bilinear_weights``); and the result is accepted only if
``verify_tensor_decomposition`` reproduces all 1,728 entries of the tensor.

**What this is not.** Not a discovery: it is a known bound made explicit. Not a proof that 42 is
the least: the least is not known. Not a quantum circuit: a circuit also pays for the linear parts,
depth and qubits, which is why an incumbent circuit can use more products than this.
"""
from __future__ import annotations

from typing import Any

import numpy as np

from apedp_dyn.quantum.field_tensor_search import (
    DEGREE,
    FIELD_ORDER,
    MODULUS_INT,
    TensorDecomposition,
    build_multiplication_tensor,
    gf_mul,
    gf_pow,
    solve_gf2_bilinear_weights,
    verify_tensor_decomposition,
)

RANK = 42
SUBFIELD_DEGREE = 3             # GF(8) over GF(2)
EXTENSION_DEGREE = 4            # GF(2^12) over GF(8)
POINTS = 2 * EXTENSION_DEGREE - 1   # values that fix a product of two polynomials of degree at most 3
SOURCE = ("Ballet, Pieltant, Rambaud, Randriambololona, Rolland, Chaumine, 'On the tensor rank of multiplication in "
          "finite extensions of finite fields and related issues in algebraic geometry', Russian Math. Surveys 76:1 "
          "(2021), arXiv:1906.07456, Table 2: the symmetric bilinear complexity of GF(2^12) over GF(2) is at most 42")


def _bits(element: int) -> np.ndarray:
    bits: np.ndarray = np.array([(element >> k) & 1 for k in range(DEGREE)], dtype=np.uint8)
    return bits


def _solve(matrix: np.ndarray, target: np.ndarray) -> np.ndarray:
    """The solution of ``matrix @ x = target`` over GF(2) for a square matrix of full rank."""
    n = matrix.shape[0]
    work = np.concatenate([matrix.copy() % 2, target.reshape(n, -1).copy() % 2], axis=1).astype(np.uint8)
    for column in range(n):
        pivot = next((row for row in range(column, n) if work[row, column]), None)
        if pivot is None:
            raise ValueError("the basis is not a basis: its matrix is singular over GF(2)")
        if pivot != column:
            work[[column, pivot]] = work[[pivot, column]]
        for row in range(n):
            if row != column and work[row, column]:
                work[row] ^= work[column]
    solved: np.ndarray = work[:, n:]
    return solved


def subfield_generator() -> int:
    """An element of order 7 in GF(2^12): it and its powers, with 0, are the copy of GF(8)."""
    theta: int = gf_pow(2, FIELD_ORDER // 7, MODULUS_INT)
    if theta == 1 or gf_pow(theta, 7, MODULUS_INT) != 1:
        raise ValueError("u^585 does not have order 7 in this representation of the field")
    return theta


def tower_basis(theta: int) -> np.ndarray:
    """The 12 by 12 matrix whose column ``3*j + i`` holds the bits of ``theta^i * u^j``: a basis over GF(2)."""
    columns = [_bits(gf_mul(gf_pow(theta, i, MODULUS_INT), gf_pow(2, j, MODULUS_INT), MODULUS_INT))
               for j in range(EXTENSION_DEGREE) for i in range(SUBFIELD_DEGREE)]
    basis: np.ndarray = np.stack(columns, axis=1)
    return basis


def evaluation_forms(theta: int) -> list[np.ndarray]:
    """For each of the 7 points, the 3 by 12 matrix taking an element's bits to its polynomial's value there.

    The element is read as a polynomial of degree at most 3 in ``u`` with coefficients in GF(8); the
    value at a point of GF(8) is again in GF(8) and is given by its three coordinates on ``1, theta,
    theta^2``. Each coordinate is a linear form in the element's 12 bits.
    """
    basis = tower_basis(theta)
    points = [0, *(gf_pow(theta, k, MODULUS_INT) for k in range(POINTS - 1))]      # 0, 1, theta, ..., theta^5
    coordinates = _solve(basis, np.eye(DEGREE, dtype=np.uint8))                   # bits -> coordinates on theta^i u^j
    forms: list[np.ndarray] = []
    for point in points:
        form: np.ndarray = np.zeros((SUBFIELD_DEGREE, DEGREE), dtype=np.uint8)
        for bit in range(DEGREE):
            value = 0
            for j in range(EXTENSION_DEGREE):                  # sum over j of (coefficient j) * point^j, in the field
                coefficient = 0
                for i in range(SUBFIELD_DEGREE):
                    if coordinates[SUBFIELD_DEGREE * j + i, bit]:
                        coefficient ^= gf_pow(theta, i, MODULUS_INT)
                value ^= gf_mul(coefficient, gf_pow(point, j, MODULUS_INT) if j else 1, MODULUS_INT)
            in_subfield = _solve(basis, _bits(value))[:, 0]    # the value lies in GF(8): only theta^i u^0 are used
            if in_subfield[SUBFIELD_DEGREE:].any():
                raise ValueError("a value of the polynomial left the copy of GF(8)")
            form[:, bit] = in_subfield[:SUBFIELD_DEGREE]
        forms.append(form)
    return forms


def build_tower_42_reference() -> TensorDecomposition:
    """The 42-product decomposition, accepted only if it reproduces the tensor exactly."""
    theta = subfield_generator()
    rows: list[np.ndarray] = []
    for form in evaluation_forms(theta):
        a0, a1, a2 = form                                   # the value's three coordinates, as forms in the bits
        rows += [a0, a1, a2, a0 ^ a1, a0 ^ a2, a1 ^ a2]     # six products multiply two 3-term polynomials over GF(2)
    U: np.ndarray = np.stack(rows).astype(np.uint8)
    tensor = build_multiplication_tensor()
    consistent, W, defects = solve_gf2_bilinear_weights(U, U, tensor)
    if not consistent or W is None:
        raise ValueError(f"the 42 products do not span the multiplication: {defects} entries cannot be met")
    decomposition = TensorDecomposition(rank=RANK, U=U, V=U.copy(), W=W, name="Tower-42-GF8",
                                        metadata=metadata(theta))
    valid, mismatches = verify_tensor_decomposition(tensor, decomposition)
    if not valid:
        raise ValueError(f"the decomposition does not reproduce the tensor: {len(mismatches)} entries differ")
    return decomposition


def metadata(theta: int) -> dict[str, Any]:
    return {"category": "literature_bound_made_explicit", "nonlinear_count": RANK, "symmetric": True,
            "construction": "GF(2^12) of degree 4 over GF(8): 7 values of a product of two cubics over GF(8), "
                            "each a multiplication in GF(8) of 6 products of bits",
            "subfield_generator": f"u^{FIELD_ORDER // 7} = {theta}", "source": SOURCE,
            "epistemic_status": "known_upper_bound_verified_exactly_not_a_minimum_rank_proof"}


# --- A circuit, gate by gate: 42 Toffolis, no extra qubits ---------------------------------------
#
# ``field_tensor_search.compile_reversible_multiplier`` prices a decomposition; it does not give a
# circuit that can be run. This does. The three registers hold x, y and z (12 qubits each, 36 in
# all); the circuit takes (x, y, z) to (x, y, z + x*y). Every product of the decomposition is one
# Toffoli: CNOTs inside the x register bring the product's linear form of x onto one qubit, the
# same in the y register, and CNOTs inside the z register make one qubit's flip add the product's
# output vector to z. The registers are left in whatever basis the last product needed and are put
# back at the end, so no qubit beyond the 36 is used.

X_REGISTER, Y_REGISTER, Z_REGISTER = 0, DEGREE, 2 * DEGREE
QUBITS = 3 * DEGREE
CNOT, TOFFOLI = "CNOT", "TOFFOLI"
Gate = tuple[str, int, int, int]            # (kind, control, second control or -1, target)


class _Basis:
    """One register under CNOTs: ``rows[q]`` is the linear form of the register's start that qubit ``q`` holds."""

    def __init__(self, offset: int, gates: list[Gate]) -> None:
        self.offset, self.gates = offset, gates
        self.rows: np.ndarray = np.eye(DEGREE, dtype=np.uint8)
        self.inverse: np.ndarray = np.eye(DEGREE, dtype=np.uint8)

    def cnot(self, control: int, target: int) -> None:
        self.rows[target] ^= self.rows[control]
        self.inverse[:, control] ^= self.inverse[:, target]
        self.gates.append((CNOT, self.offset + control, -1, self.offset + target))

    def hold(self, form: np.ndarray) -> int:
        """Put ``form`` (of the register's start) on one qubit; which one."""
        support = [int(q) for q in np.flatnonzero((form.astype(np.int64) @ self.inverse) % 2)]
        if not support:
            raise ValueError("a product's linear form is zero")
        pivot = max(support, key=lambda q: (int(self.rows[q].sum()), q))
        for other in support:
            if other != pivot:
                self.cnot(other, pivot)
        return pivot

    def flip_adds(self, vector: np.ndarray) -> int:
        """Arrange that flipping one qubit adds ``vector`` to the register's logical value; which one."""
        support = [int(q) for q in np.flatnonzero((self.rows.astype(np.int64) @ vector) % 2)]
        if not support:
            raise ValueError("a product's output vector is zero")
        pivot = max(support, key=lambda q: (int(self.inverse[:, q].sum()), q))
        for other in support:
            if other != pivot:
                self.cnot(pivot, other)
        return pivot

    def restore(self) -> None:
        """Back to the start: every qubit holds its own bit again."""
        for column in range(DEGREE):
            if not self.rows[column, column]:
                source = next(q for q in range(column + 1, DEGREE) if self.rows[q, column])
                self.cnot(source, column)
            for other in range(DEGREE):
                if other != column and self.rows[other, column]:
                    self.cnot(column, other)


def build_netlist(decomposition: TensorDecomposition) -> list[Gate]:
    """A gate list for ``z += x*y`` with one Toffoli per product and no qubit beyond the three registers."""
    gates: list[Gate] = []
    x, y, z = (_Basis(offset, gates) for offset in (X_REGISTER, Y_REGISTER, Z_REGISTER))
    for u, v, w in zip(decomposition.U, decomposition.V, decomposition.W, strict=True):
        a, b, target = x.hold(u), y.hold(v), z.flip_adds(w)
        gates.append((TOFFOLI, X_REGISTER + a, Y_REGISTER + b, Z_REGISTER + target))
    for register in (x, y, z):
        register.restore()
    return gates


def replay(gates: list[Gate]) -> dict[str, Any]:
    """What a gate list computes, worked out from the gates alone (nothing of the builder is used).

    CNOTs must stay inside a register and a Toffoli must take one control from x, one from y and
    its target in z; then x and y only ever hold linear forms of their start and z holds its start
    plus a sum of products of those forms. The sum is returned as a 12 by 12 by 12 tensor, with
    whether each register ends as it began. If the tensor equals the field's and the registers are
    restored, the circuit is right on every one of the 2^36 basis states, and so on every state.
    """
    forms: dict[int, np.ndarray] = {offset: np.eye(DEGREE, dtype=np.uint8)
                                    for offset in (X_REGISTER, Y_REGISTER, Z_REGISTER)}
    tensor: np.ndarray = np.zeros((DEGREE, DEGREE, DEGREE), dtype=np.uint8)
    counts = {CNOT: 0, TOFFOLI: 0}
    for kind, control, second, target in gates:
        if kind not in counts:
            raise ValueError(f"unknown gate {kind!r}")
        counts[kind] += 1
        if kind == CNOT:
            offset = (control // DEGREE) * DEGREE
            if target // DEGREE != control // DEGREE or control == target:
                raise ValueError("a CNOT leaves its register")
            forms[offset][target - offset] ^= forms[offset][control - offset]
        else:
            if not (control // DEGREE == 0 and second // DEGREE == 1 and target // DEGREE == 2):
                raise ValueError("a Toffoli is not from x and y into z")
            added = _solve(forms[Z_REGISTER], np.eye(DEGREE, dtype=np.uint8))[:, target - Z_REGISTER]
            tensor ^= np.einsum("i,j,k->ijk", forms[X_REGISTER][control], forms[Y_REGISTER][second - Y_REGISTER], added)
    identity: np.ndarray = np.eye(DEGREE, dtype=np.uint8)
    return {"tensor": tensor, "toffolis": counts[TOFFOLI], "cnots": counts[CNOT], "qubits": QUBITS,
            "registers_restored": all(np.array_equal(forms[offset], identity) for offset in forms)}


def run(gates: list[Gate], x: int, y: int, z: int) -> tuple[int, int, int]:
    """The gate list applied to one basis state, bit by bit: a second check that shares nothing with ``replay``."""
    state = x | (y << Y_REGISTER) | (z << Z_REGISTER)
    for kind, control, second, target in gates:
        if (state >> control) & 1 and (kind == CNOT or (state >> second) & 1):
            state ^= 1 << target
    mask = (1 << DEGREE) - 1
    return state & mask, (state >> Y_REGISTER) & mask, (state >> Z_REGISTER) & mask


def build_tower_42_circuit() -> tuple[list[Gate], dict[str, Any]]:
    """The 42-Toffoli circuit and its account, accepted only if ``replay`` reproduces the field's tensor."""
    gates = build_netlist(build_tower_42_reference())
    account = replay(gates)
    if not (np.array_equal(account.pop("tensor"), build_multiplication_tensor()) and account["registers_restored"]):
        raise ValueError("the circuit does not compute z + x*y and restore x and y")
    return gates, account
