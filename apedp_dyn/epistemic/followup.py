"""Closed-loop follow-up (v1): execute a pointer recommendation, re-adjudicate.

This closes "identify missing information -> recover later" for one deficit
type: weak_intervention. Given a pointer Recommendation with
evidence_deficit == "weak_intervention", a problem, and the two rival IRs,
it rebuilds the problem with an escalated holdout drive, refits both
structures, and re-adjudicates. Any other deficit returns an unacted record;
the module never invents experiments for deficits it cannot execute.

The follow-up outcome (recovered / still-ambiguous / worse) is REPORTED.
Nothing here alters gates, adjudication, or prior artifacts.
"""
from __future__ import annotations

import dataclasses
from typing import Any

import numpy as np

from apedp_dyn.epistemic.adjudicate import adjudicate
from apedp_dyn.epistemic.pointer import Recommendation
from apedp_dyn.fitting.parameter_fit import fit_candidate
from apedp_dyn.problems.base import finalize

FOLLOWUP_VERSION = "1.0.0-escalate"


def escalate_holdout(problem, factor: float):
    """Rebuild a problem with the holdout drive scaled by factor.

    Train regime, splits, thresholds, and ICs are untouched; ground truth is
    regenerated by finalize, so the follow-up is a genuinely new experiment,
    not a replay.
    """
    if not np.isfinite(factor) or factor <= 0:
        raise ValueError(f"escalation factor must be positive finite, got {factor!r}")
    holdout = dict(problem.holdout)
    base_u = holdout["u_of_t"]
    holdout["u_of_t"] = lambda t, _u=base_u, _f=float(factor): \
        _f * np.asarray(_u(t), dtype=float)
    return finalize(dataclasses.replace(problem, holdout=holdout))


def followup_weak_intervention(problem, truth_ir, rival_ir, rec: Recommendation,
                               factor: float) -> dict[str, Any]:
    """Execute a weak-intervention recommendation and re-adjudicate."""
    if rec.evidence_deficit != "weak_intervention":
        return {"acted": False,
                "reason": f"deficit {rec.evidence_deficit!r} not executable by v1 follow-up"}
    before = adjudicate([fit_candidate(problem, truth_ir),
                         fit_candidate(problem, rival_ir)])
    after_prob = escalate_holdout(problem, factor)
    after = adjudicate([fit_candidate(after_prob, truth_ir),
                        fit_candidate(after_prob, rival_ir)])
    return {
        "acted": True, "factor": float(factor),
        "followup_version": FOLLOWUP_VERSION,
        "before": before.status.value, "after": after.status.value,
        "promoted_after": (after.promoted.candidate.candidate_id
                           if after.promoted is not None else None),
        "recovered": bool(after.status.value == "unique_support"
                          and after.promoted is not None
                          and after.promoted.candidate.candidate_id
                          == truth_ir.candidate_id),
    }
